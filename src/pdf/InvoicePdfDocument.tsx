import { Document, Page, Text, View, StyleSheet, Image } from "@react-pdf/renderer";
import { format } from "date-fns";

export interface InvoicePdfItemRow {
  itemName?: string;
  hsnCode?: string;
  quantity?: number;
  pricePerItem?: number;
  taxAmount?: number;
  taxPercentage?: number;
  totalAmount?: number;
}

export interface InvoicePdfBusiness {
  businessName?: string;
  name?: string;
  gstin?: string;
  address?: string;
  state?: string;
  logoUrl?: string;
  phone?: string;
  email?: string;
}

export interface InvoicePdfBankAccount {
  bankName?: string;
  accountNumber?: string;
  ifsc?: string;
  upiId?: string;
}

export interface InvoicePdfDocumentProps {
  type: "SALE" | "PURCHASE";
  invoiceNo: string;
  invoiceDate?: string | Date | null;
  dueDate?: string | Date | null;
  partyName: string;
  partyMobile?: string;
  partyGst?: string;
  items: InvoicePdfItemRow[];
  taxable: number;
  tax: number;
  additionalCharges: number;
  discountAfterTax: number;
  total: number;
  paid: number;
  due: number;
  status: string;
  notes?: string;
  termsAndConditions?: string;
  business: InvoicePdfBusiness;
  /** Present only for a generated GST e-Invoice — omitted, this section just doesn't render. */
  eInvoice?: { irn: string; qrDataUrl: string | null };
  /** The business's payout bank account, when one with a UPI ID exists. */
  bankAccount?: InvoicePdfBankAccount;
  /** Pre-rendered "Scan to Pay" UPI QR — generated by the caller (async), not here. */
  paymentQrDataUrl?: string | null;
}

const ACCENT = "#2563eb";
const INK = "#1e293b";
const MUTED = "#64748b";
const BORDER = "#e2e8f0";
const PANEL = "#f8fafc";

const inr = (v: unknown) => `Rs. ${Number(v || 0).toLocaleString("en-IN")}`;
const fmtDate = (v: unknown) => {
  if (!v) return "-";
  const d = new Date(v as string);
  return isNaN(d.getTime()) ? "-" : format(d, "dd MMM yyyy");
};

const STATUS_COLOR: Record<string, { bg: string; fg: string }> = {
  PAID: { bg: "#dcfce7", fg: "#166534" },
  PARTIAL: { bg: "#fef9c3", fg: "#854d0e" },
  UNPAID: { bg: "#fee2e2", fg: "#991b1b" },
  VOID: { bg: "#f1f5f9", fg: "#475569" },
};

