/**
 * Single source of truth for both the in-app preview (PDFViewer) and the
 * downloaded file (PDFDownloadLink) — same component, same output.
 */
export function InvoicePdfDocument(props: InvoicePdfDocumentProps) {
  const { business } = props;
  const businessName = business.businessName?.trim() || business.name?.trim() || "Your Business";
  const statusColor = STATUS_COLOR[props.status] || STATUS_COLOR.UNPAID;

  // Bottom-left slot: real payout details if we have a bank account with a
  // UPI ID (real "Scan to Pay" QR), else the GST e-Invoice IRN/QR when this
  // invoice has one, else the slot is simply omitted — never fabricated.
  const showPayment = !!(props.bankAccount && props.paymentQrDataUrl);
  const showEInvoice = !showPayment && !!props.eInvoice;

  return (
    <Document title={`Invoice ${props.invoiceNo}`}>
      <Page size="A4" style={styles.page}>
        {/* Header */}
        <View style={styles.headerRow}>
          <View>
            {business.logoUrl ? <Image src={business.logoUrl} style={styles.logo} /> : null}
            <Text style={styles.businessName}>{businessName}</Text>
            {business.phone ? <Text style={styles.muted}>{business.phone}</Text> : null}
            {business.email ? <Text style={styles.muted}>{business.email}</Text> : null}
            {business.gstin ? <Text style={styles.muted}>GSTIN: {business.gstin}</Text> : null}
            {business.address ? <Text style={styles.muted}>{business.address}</Text> : null}
            {business.state ? <Text style={styles.muted}>{business.state}</Text> : null}
          </View>
          <View>
            <Text style={styles.pill}>
              {props.type === "SALE" ? "TAX INVOICE" : "PURCHASE BILL"}
            </Text>
            <View style={styles.metaBlock}>
              <View style={styles.metaRow}>
                <Text style={styles.metaLabel}>Invoice No:</Text>
                <Text style={styles.metaValue}>{props.invoiceNo || "-"}</Text>
              </View>
              <View style={styles.metaRow}>
                <Text style={styles.metaLabel}>Date:</Text>
                <Text style={styles.metaValue}>{fmtDate(props.invoiceDate)}</Text>
              </View>
              <View style={styles.metaRow}>
                <Text style={styles.metaLabel}>Due Date:</Text>
                <Text style={styles.metaValue}>{fmtDate(props.dueDate)}</Text>
              </View>
            </View>
          </View>
        </View>

        <View style={styles.divider} />

        {/* Bill To / Status */}
        <View style={styles.boxRow}>
          <View style={styles.box}>
            <Text style={styles.boxLabel}>{props.type === "SALE" ? "Bill To" : "Supplier"}</Text>
            <Text style={styles.boxTitle}>{props.partyName}</Text>
            {props.partyMobile ? <Text style={styles.muted}>{props.partyMobile}</Text> : null}
            {props.partyGst ? <Text style={styles.muted}>GSTIN: {props.partyGst}</Text> : null}
          </View>
          <View style={styles.box}>
            <Text style={styles.boxLabel}>Payment Status</Text>
            <Text
              style={[
                styles.statusPill,
                { backgroundColor: statusColor.bg, color: statusColor.fg },
              ]}
            >
              {props.status}
            </Text>
            <Text style={styles.muted}>
              {props.type === "SALE" ? "Received" : "Paid"}: {inr(props.paid)}
            </Text>
            <Text style={styles.muted}>Balance Due: {inr(props.due)}</Text>
          </View>
        </View>

        {/* Line items */}
        <Text style={styles.sectionHeading}>Line Items</Text>
        <View style={styles.table}>
          <View style={styles.tableHeader}>
            <Text style={[styles.tableHeaderText, styles.colItem]}>Description</Text>
            <Text style={[styles.tableHeaderText, styles.colHsn]}>HSN</Text>
            <Text style={[styles.tableHeaderText, styles.colQty]}>Qty</Text>
            <Text style={[styles.tableHeaderText, styles.colPrice]}>Rate</Text>
            <Text style={[styles.tableHeaderText, styles.colTax]}>Tax</Text>
            <Text style={[styles.tableHeaderText, styles.colAmount]}>Amount</Text>
          </View>
          {props.items.map((row, i) => (
            <View
              style={[styles.tableRow, ...(i % 2 === 1 ? [styles.tableRowAlt] : [])]}
              key={i}
            >
              <Text style={styles.colItem}>{row.itemName || "-"}</Text>
              <Text style={styles.colHsn}>{row.hsnCode || "-"}</Text>
              <Text style={styles.colQty}>{row.quantity ?? 0}</Text>
              <Text style={styles.colPrice}>{inr(row.pricePerItem)}</Text>
              <Text style={styles.colTax}>
                {inr(row.taxAmount)}
                {row.taxPercentage ? ` (${row.taxPercentage}%)` : ""}
              </Text>
              <Text style={styles.colAmount}>{inr(row.totalAmount)}</Text>
            </View>
          ))}
        </View>

        {/* Summary heading */}
        <View style={styles.summaryRow}>
          <Text style={styles.sectionHeading}>Summary</Text>
          <Text style={{ fontSize: 11, fontWeight: 700 }}>Total: {inr(props.total)}</Text>
        </View>

        {/* Payment/e-Invoice box + Totals breakdown */}
        <View style={styles.bottomRow}>
          {showPayment && (
            <View style={styles.paymentBox}>
              <Text style={styles.boxLabel}>Payment Details</Text>
              {props.bankAccount?.bankName ? (
                <View style={styles.paymentRow}>
                  <Text style={styles.muted}>Bank</Text>
                  <Text style={styles.metaValue}>{props.bankAccount.bankName}</Text>
                </View>
              ) : null}
              {props.bankAccount?.accountNumber ? (
                <View style={styles.paymentRow}>
                  <Text style={styles.muted}>Account No.</Text>
                  <Text style={styles.metaValue}>{props.bankAccount.accountNumber}</Text>
                </View>
              ) : null}
              {props.bankAccount?.ifsc ? (
                <View style={styles.paymentRow}>
                  <Text style={styles.muted}>IFSC</Text>
                  <Text style={styles.metaValue}>{props.bankAccount.ifsc}</Text>
                </View>
              ) : null}
              <Text style={[styles.boxLabel, { marginTop: 8 }]}>Scan to Pay</Text>
              {props.paymentQrDataUrl ? (
                <Image src={props.paymentQrDataUrl} style={styles.qrImage} />
              ) : null}
            </View>
          )}
          {showEInvoice && (
            <View style={styles.paymentBox}>
              <Text style={styles.boxLabel}>e-Invoice Verification</Text>
              <Text style={[styles.footerText, { marginTop: 2 }]}>
                IRN: {props.eInvoice!.irn}
              </Text>
              {props.eInvoice!.qrDataUrl ? (
                <Image src={props.eInvoice!.qrDataUrl} style={styles.qrImage} />
              ) : null}
            </View>
          )}

          <View style={styles.totalsBox}>
            <View style={styles.totalRow}>
              <Text style={styles.muted}>Taxable Amount</Text>
              <Text>{inr(props.taxable)}</Text>
            </View>
            <View style={styles.totalRow}>
              <Text style={styles.muted}>Total Tax</Text>
              <Text>{inr(props.tax)}</Text>
            </View>
            <View style={styles.totalRow}>
              <Text style={styles.muted}>Additional Charges</Text>
              <Text>{inr(props.additionalCharges)}</Text>
            </View>
            <View style={styles.totalRow}>
              <Text style={styles.muted}>Discount</Text>
              <Text>- {inr(props.discountAfterTax)}</Text>
            </View>
            <View style={styles.grandRow}>
              <Text>Grand Total</Text>
              <Text>{inr(props.total)}</Text>
            </View>
            <View style={styles.totalRow}>
              <Text style={styles.muted}>{props.type === "SALE" ? "Received" : "Paid"}</Text>
              <Text>{inr(props.paid)}</Text>
            </View>
            <View style={styles.balanceRow}>
              <Text style={styles.balanceLabel}>Balance Due</Text>
              <Text style={styles.balanceValue}>{inr(props.due)}</Text>
            </View>
          </View>
        </View>

        {/* Notes / Terms */}
        {(props.notes || props.termsAndConditions) && (
          <View style={styles.footerRow}>
            <View style={styles.footerCol}>
              {props.notes ? (
                <>
                  <Text style={styles.footerHeading}>Notes</Text>
                  <Text style={styles.footerText}>{props.notes}</Text>
                </>
              ) : null}
            </View>
            <View style={styles.footerCol}>
              {props.termsAndConditions ? (
                <>
                  <Text style={styles.footerHeading}>Terms &amp; Conditions</Text>
                  <Text style={styles.footerText}>{props.termsAndConditions}</Text>
                </>
              ) : null}
            </View>
          </View>
        )}

        <View style={styles.signatureArea}>
          <View style={styles.signatureLine}>
            <Text style={styles.signatureLabel}>Authorized Signature</Text>
          </View>
        </View>
      </Page>
    </Document>
  );
}
