  businessName: { fontSize: 15, fontWeight: 700, color: INK, marginBottom: 2 },
  muted: { color: MUTED },
  metaLabel: { color: MUTED },
  metaValue: { fontWeight: 700, color: INK },
  pill: {
    backgroundColor: ACCENT,
    color: "#ffffff",
    fontSize: 11,
    fontWeight: 700,
    paddingVertical: 6,
    paddingHorizontal: 14,
    borderRadius: 5,
    alignSelf: "flex-end",
  },
  metaBlock: { marginTop: 8, alignItems: "flex-end" },
  metaRow: { flexDirection: "row", gap: 4, marginTop: 3 },

  divider: { borderBottomWidth: 1, borderBottomColor: BORDER, marginTop: 16, marginBottom: 16 },

  // Two-box row
  boxRow: { flexDirection: "row", gap: 12, marginBottom: 16 },
